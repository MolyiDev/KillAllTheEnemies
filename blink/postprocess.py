"""Keep oversized generated server serializers out of the native-code budget, and format the output.

Blink 0.18.8 always emits --!native and has no setting to suppress that header. Run after generation; protocol and
generated function bodies are untouched.
"""
from pathlib import Path
import subprocess

root = Path(__file__).resolve().parent.parent / "src/Global"
for name in ("Network", "NetworkMeta"):
    path = root / "Server" / f"{name}.luau"
    source = path.read_text()
    assert "File generated by Blink" in source[:400], f"unexpected generated file {path}"
    path.write_text(source.replace("--!native\n", "", 1))
